import {build} from 'esbuild';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
await mkdir('work/tests',{recursive:true});
await build({stdin:{resolveDir:process.cwd(),contents:`export * as D from './lib/domain';export * as W from './lib/workflow';export * as A from './lib/stage-actions';export * as S from './lib/general-script-source';export {generalCandidateAction} from './lib/general-scenario-workflow';export {applyFilmSettings} from './lib/film-settings';`},bundle:true,platform:'node',format:'esm',outfile:'work/tests/stage-lifecycle.mjs'});
const {D,W,A,S,generalCandidateAction,applyFilmSettings}=await import('../work/tests/stage-lifecycle.mjs');
const p=D.newProject('Проверка'),item=p.items[0];
const original=D.addVariant(p,item.id,{text:'Авторский сюжет',title:'Исходный'});D.approve(p,item.id);
const alt=D.addVariant(p,item.id,{text:'Доработанный сюжет',title:'Альтернатива'});
assert.equal(S.generalScriptSource(p).variant.id,original.id,'Selection cannot change the fixed generation source');
assert.throws(()=>S.assertGeneralScriptSource(p,alt.id),/Основной сценарий изменился/);
const hashes=[4,5,6,7,8].map(s=>D.dependencies(p,s)),materials=structuredClone(p.items);
A.applyStageAction(p,{stage:0,operation:'rework'});
assert(!W.stageComplete(p,0));assert(!W.workflowReady(p,12));assert(!D.stageReady(p,5));
assert.deepEqual(p.items,materials,'Starting revision preserves every artifact and previous seal');
assert.deepEqual([4,5,6,7,8].map(s=>D.dependencies(p,s)),hashes,'Starting revision does not invalidate hashes');
const restored=JSON.parse(JSON.stringify(p));assert(!W.stageComplete(restored,0),'Rework persists after reload');
assert.equal(S.generalScriptSource(restored).variant.id,original.id);
generalCandidateAction(restored,{operation:'approve',target:{kind:'variant',itemId:item.id,variantId:original.id}});
assert(W.stageComplete(restored,0));assert(W.workflowReady(restored,12));
assert.deepEqual([4,5,6,7,8].map(s=>D.dependencies(restored,s)),hashes,'Reapproving the same script restores dependencies');
generalCandidateAction(p,{operation:'approve',target:{kind:'variant',itemId:item.id,variantId:alt.id}});
assert(W.stageComplete(p,0));assert.equal(S.generalScriptSource(p).variant.id,alt.id);
assert.equal(p.items[0].variants.length,2,'Promoting right keeps the old script in history');
assert.notEqual(D.dependencies(p,5),hashes[1],'Actual change invalidates its dependants');
A.applyStageAction(p,{stage:1,operation:'rework'});
const before=structuredClone(p);
assert.throws(()=>A.applyStageAction(p,{stage:1,operation:'approve'}),/готового выбранного/);
assert.deepEqual(p,before,'Incomplete approval fails atomically without clearing revision');
assert.throws(()=>A.applyStageAction(p,{stage:1,operation:'skip'}),/обязательные/);
assert.throws(()=>A.applyStageAction(p,{stage:5,operation:'approve'}),/Сначала завершите/);
delete p.stageReviews[1];
p.captions=[{id:'caption',planId:'x',enabled:true,text:'Заголовок'}];
A.applyStageAction(p,{stage:10,operation:'skip'});assert.equal(p.captions[0].text,'Заголовок');assert(!p.captions[0].enabled);assert(W.stageComplete(p,10));
A.applyStageAction(p,{stage:11,operation:'skip'});assert(!p.music.settings.enabled);assert(W.stageComplete(p,11));
A.applyStageAction(p,{stage:10,operation:'rework'});assert(!W.stageComplete(p,10));assert(!W.workflowReady(p,8));
const settings={title:p.title,seconds:p.seconds,format:p.format,limit:null,screenplayModel:'gpt-6-astra'};
const config=p.configVersion;applyFilmSettings(p,settings);assert.equal(S.screenplayModel(p),'gpt-6-astra');assert.equal(p.configVersion,config);
assert.throws(()=>applyFilmSettings(p,{...settings,screenplayModel:'made-up'}));
const fresh=D.newProject('Новый');assert.equal(S.generalScriptSource(fresh),undefined);
const src=D.addVariant(fresh,fresh.items[0].id,{text:'Первый текст'});assert.equal(S.generalScriptSource(fresh).variant.id,src.id);
console.log('PASS stage lifecycle: persistent rework, blocked progression, unchanged artifact seals, same-text approval, promotion, atomic validation, optional skip, model settings');
